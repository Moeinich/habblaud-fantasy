/** Rows of a capital: the wordmark is 8 rows tall (7 + shadow), or 10 when a descender hangs below the baseline. */
const CAP = 7;

/** Glyph for a character: the font, then the letter without accents (é → e), then "?". */
function glyph(ch: string): readonly string[] {
  return FONT[ch] ?? FONT[ch.normalize('NFD').replace(/[\u0300-\u036f]/g, '')] ?? FONT['?'];
}

/** Characters the font draws without falling back to "?" (accented Latin letters count). */
export function wordmarkSupports(ch: string): boolean {
  return ch in FONT || ch.normalize('NFD').replace(/[\u0300-\u036f]/g, '') in FONT;
}

/**
 * Where the gold part starts: at an explicit "|" marker ("swift|c" → "swift" + "c"). Otherwise "Habblaud" keeps its "Hab" + "blaud"; otherwise the first word (two words), a camelCase
 * hump ("SwiftCode" → "Swift" + "Code"), the end of an uppercase run before lowercase ("SWIFTc" → "SWIFT" + "c"),
 * or the first three eighths of the name.
 */
export function wordmarkSplit(name: string): number {
  const marker = [...name].indexOf('|');
  if (marker > 0) return marker;
  const chars = [...name];
  const n = chars.length;
  if (n < 2) return n;
  const space = chars.indexOf(' ');
  if (space > 0) return space;
  const upper = (c: string) => c !== c.toLowerCase() && c === c.toUpperCase();
  const lower = (c: string) => c !== c.toUpperCase() && c === c.toLowerCase();
  for (let i = 1; i < n; i++) if (lower(chars[i - 1]) && upper(chars[i])) return i;
  let run = 0;
  while (run < n && upper(chars[run])) run++;
  if (run >= 2 && run < n && lower(chars[run])) return run;
  return Math.min(n - 1, Math.max(1, Math.round((n * 3) / 8)));
}

/**
 * The wordmark as pixelIcon rows: 'c' = parchment part, 't' = gold part, 's' = shadow, '.' = empty. Every row has
 * the same length; the height is 8, or 10 when some letter has a descender.
 */
export function wordmarkRows(name: string): string[] {
  const split = wordmarkSplit(name);
  const chars = [...name].filter((c, i) => !(c === '|' && i === split));
  const glyphs = chars.map(glyph);
  const ink = Math.max(CAP, ...glyphs.map((g) => g.length));
  const height = ink + 1;
  const width = Math.max(1, glyphs.reduce((sum, g) => sum + g[0].length, 0) + Math.max(0, glyphs.length - 1));
  const grid: string[][] = Array.from({ length: height }, () => Array<string>(width).fill('.'));
  let x = 0;
  glyphs.forEach((g, i) => {
    const color = i < split ? 'c' : 't';
    g.forEach((row, y) => {
      for (let dx = 0; dx < row.length; dx++) if (row[dx] === '#') grid[y][x + dx] = color;
    });
    x += g[0].length + 1;
  });
  // Drop shadow: 1 px straight below every inked pixel that has nothing under it.
  for (let y = height - 1; y >= 1; y--) {
    for (let col = 0; col < width; col++) {
      const above = grid[y - 1][col];
      if (grid[y][col] === '.' && (above === 'c' || above === 't')) grid[y][col] = 's';
    }
  }
  return grid.map((r) => r.join(''));
}
